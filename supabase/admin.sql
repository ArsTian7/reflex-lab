-- ---------- 0. bcrypt 支持 ----------
create extension if not exists pgcrypto with schema extensions;

-- ---------- 1. 管理员密码（单行表，RLS 无策略 = 匿名完全不可读写）----------
create table if not exists public.admin_secret (
  id            integer primary key default 1,
  password_hash text        not null,
  updated_at    timestamptz not null default now(),
  constraint admin_secret_single_row check (id = 1)
);
alter table public.admin_secret enable row level security;

-- ---------- 2. 密码失败记录（防暴力破解，按 IP 限流）----------
create table if not exists public.admin_attempts (
  id         bigint generated by default as identity primary key,
  ip         text,
  created_at timestamptz not null default now()
);
alter table public.admin_attempts enable row level security;
create index if not exists admin_attempts_ip_idx on public.admin_attempts (ip, created_at desc);

-- ---------- 3. 黑名单（昵称 + 设备指纹，封了就不能再上榜）----------
create table if not exists public.banned_players (
  id         bigint generated by default as identity primary key,
  name       text,
  device_id  text,
  reason     text,
  created_at timestamptz not null default now()
);
alter table public.banned_players enable row level security;
drop policy if exists "ban list readable" on public.banned_players;
create policy "ban list readable"
  on public.banned_players for select
  to anon, authenticated
  using (true);
create unique index if not exists banned_players_name_idx
  on public.banned_players (lower(btrim(name))) where name is not null;

-- ---------- 4. 密码校验（所有管理操作的第一步）----------
create or replace function public.admin_verify(p_password text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $fn$
declare
  v_hash  text;
  v_ip    text;
  v_fails integer;
begin
  begin
    v_ip := coalesce(nullif(split_part(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ',', 1), ''), 'unknown');
  exception when others then
    v_ip := 'unknown';
  end;

  select count(*) into v_fails
    from public.admin_attempts
   where ip = v_ip and created_at > now() - interval '10 minutes';
  if v_fails >= 12 then
    raise exception '尝试次数过多，请 10 分钟后再试' using errcode = '53400';
  end if;

  select password_hash into v_hash from public.admin_secret where id = 1;
  if v_hash is null then
    raise exception '还没有设置管理员密码，请先在 SQL Editor 里执行 admin.sql 末尾的语句' using errcode = '53400';
  end if;
  if p_password is null or crypt(p_password, v_hash) <> v_hash then
    insert into public.admin_attempts (ip) values (v_ip);
    raise exception '密码错误' using errcode = '28P01';
  end if;

  delete from public.admin_attempts where ip = v_ip and created_at < now() - interval '1 hour';
  return true;
end
$fn$;

-- ---------- 5. 删除 / 封禁 / 改密码 ----------
create or replace function public.admin_delete_score(p_password text, p_id bigint)
returns integer
language plpgsql security definer set search_path = public, extensions
as $fn$
declare v_count integer;
begin
  perform public.admin_verify(p_password);
  delete from public.scores where id = p_id;
  get diagnostics v_count = row_count;
  return v_count;
end
$fn$;

create or replace function public.admin_delete_player(p_password text, p_name text)
returns integer
language plpgsql security definer set search_path = public, extensions
as $fn$
declare v_count integer;
begin
  perform public.admin_verify(p_password);
  if coalesce(btrim(p_name), '') = '' then
    raise exception '昵称不能为空' using errcode = '22023';
  end if;
  delete from public.scores where lower(btrim(player_name)) = lower(btrim(p_name));
  get diagnostics v_count = row_count;
  return v_count;
end
$fn$;

create or replace function public.admin_ban_player(p_password text, p_name text, p_device text default null, p_reason text default null)
returns void
language plpgsql security definer set search_path = public, extensions
as $fn$
declare v_name text; v_device text;
begin
  perform public.admin_verify(p_password);
  v_name   := nullif(btrim(coalesce(p_name, '')), '');
  v_device := nullif(btrim(coalesce(p_device, '')), '');
  if v_name is null and v_device is null then
    raise exception '昵称和设备指纹至少要有一个' using errcode = '22023';
  end if;
  insert into public.banned_players (name, device_id, reason)
  values (v_name, v_device, nullif(btrim(coalesce(p_reason, '')), ''));
end
$fn$;

create or replace function public.admin_unban(p_password text, p_ban_id bigint)
returns void
language plpgsql security definer set search_path = public, extensions
as $fn$
begin
  perform public.admin_verify(p_password);
  delete from public.banned_players where id = p_ban_id;
end
$fn$;

create or replace function public.admin_change_password(p_current text, p_new text)
returns void
language plpgsql security definer set search_path = public, extensions
as $fn$
begin
  perform public.admin_verify(p_current);
  if p_new is null or length(p_new) < 6 then
    raise exception '新密码至少 6 位' using errcode = '22023';
  end if;
  update public.admin_secret
     set password_hash = crypt(p_new, gen_salt('bf', 10)),
         updated_at    = now()
   where id = 1;
  delete from public.admin_attempts;
end
$fn$;

-- ---------- 6. 让提交接口认识黑名单 ----------
create or replace function public.limit_score_rate()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  recent_name   integer;
  recent_device integer;
begin
  new.player_name := btrim(left(new.player_name, 14));

  if exists (
    select 1 from public.banned_players b
     where (b.name is not null and lower(btrim(b.name)) = lower(new.player_name))
        or (b.device_id is not null and new.device_id is not null and b.device_id = new.device_id)
  ) then
    raise exception '这个昵称或设备已被管理员封禁' using errcode = '53400';
  end if;

  select count(*) into recent_name
    from public.scores
   where lower(btrim(player_name)) = lower(new.player_name)
     and created_at > now() - interval '1 minute';

  select count(*) into recent_device
    from public.scores
   where device_id is not null
     and device_id = new.device_id
     and created_at > now() - interval '1 minute';

  if recent_name >= 6 or recent_device >= 12 then
    raise exception '提交过于频繁，请休息一下再来' using errcode = '53400';
  end if;
  return new;
end
$fn$;

