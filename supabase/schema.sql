-- ---------- 1. 成绩表 ----------
create table if not exists public.scores (
  id            bigint generated by default as identity primary key,
  player_name   text        not null,
  avatar        text        not null default 'preset:cat',
  average_ms    numeric(7,1) not null,
  best_ms       integer     not null,
  worst_ms      integer     not null,
  false_starts  smallint    not null default 0,
  trials        smallint    not null default 10,
  month_key     text        not null,
  refresh_hz    smallint,
  platform      text,
  device_id     text,
  raw           jsonb,
  created_at    timestamptz not null default now(),
  constraint scores_name_len   check (char_length(btrim(player_name)) between 1 and 14),
  constraint scores_avatar_len check (char_length(avatar) <= 20000),
  constraint scores_avg_range  check (average_ms >= 55 and average_ms <= 5000),
  constraint scores_best_range check (best_ms >= 40 and best_ms <= 5000),
  constraint scores_fs_range   check (false_starts between 0 and 50),
  constraint scores_trials     check (trials between 1 and 50),
  constraint scores_month_fmt  check (month_key ~ '^\d{4}-\d{2}$')
);

create index if not exists scores_average_idx on public.scores (average_ms);
create index if not exists scores_month_idx   on public.scores (month_key, average_ms);
create index if not exists scores_name_idx    on public.scores (lower(btrim(player_name)));
create index if not exists scores_device_idx  on public.scores (device_id, created_at desc);

-- ---------- 2. 行级权限：匿名可读、可插；不可改、不可删 ----------
alter table public.scores enable row level security;

drop policy if exists "scores readable by everyone" on public.scores;
create policy "scores readable by everyone"
  on public.scores for select
  to anon, authenticated
  using (true);

drop policy if exists "scores insertable by everyone" on public.scores;
create policy "scores insertable by everyone"
  on public.scores for insert
  to anon, authenticated
  with check (true);

-- 故意不建 update / delete 策略：前端拿到的 anon key 只能提交成绩

-- ---------- 3. 频率限制：挡住脚本刷榜 ----------
create or replace function public.limit_score_rate()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  new.player_name := btrim(left(new.player_name, 14));

  select count(*) into recent_name
    from public.scores
   where lower(btrim(player_name)) = lower(new.player_name)
     and created_at > now() - interval '1 minute';

  select count(*) into recent_device
    from public.scores
   where device_id is not null
     and device_id = new.device_id
     and created_at > now() - interval '1 minute';

  if recent_name >= 6 or recent_device >= 12 then
    raise exception '提交过于频繁，请休息一下再来' using errcode = '53400';
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_limit_score_rate on public.scores;
create trigger trg_limit_score_rate
  before insert on public.scores
  for each row execute function public.limit_score_rate();

-- ---------- 4. 排行榜视图：同名只留最快的一次平均成绩 ----------
create or replace view public.leaderboard_all
with (security_invoker = true) as
select distinct on (lower(btrim(player_name)))
  btrim(player_name) as player_name,
  avatar, average_ms, best_ms, worst_ms,
  false_starts, trials, month_key, created_at
from public.scores
order by lower(btrim(player_name)), average_ms asc, created_at asc;

create or replace view public.leaderboard_month
with (security_invoker = true) as
select * from public.leaderboard_all
where month_key = to_char((now() at time zone 'Asia/Shanghai'), 'YYYY-MM');

grant select on public.leaderboard_all   to anon, authenticated;
grant select on public.leaderboard_month to anon, authenticated;

